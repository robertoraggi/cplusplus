import { cpy_header } from "./cpy_header.ts";
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

interface AttributeDef {
  name: string;
  spellings: string[];
  arguments?: string[];
  optionalArguments?: boolean;
  availability?: "webassembly" | "device";
  cplusplus?: boolean;
  subjects: string;
  documentation: string;
}

interface Spelling {
  syntax: "kGnu" | "kCxx" | "kAsmLabel";
  attributeNamespace: string;
  name: string;
  kind: string;
}

const syntaxOrder = ["kGnu", "kCxx", "kAsmLabel"];

const availabilities = new Map<string | undefined, string>([
  [undefined, "kAlways"],
  ["webassembly", "kWebAssembly"],
  ["device", "kDeviceProfile"],
]);

function kindOf(attribute: AttributeDef): string {
  return (
    "k" +
    attribute.name
      .split("_")
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join("")
  );
}

function spellingOf(attribute: AttributeDef, spelling: string): Spelling {
  const kind = kindOf(attribute);
  if (spelling === "GNU")
    return { syntax: "kGnu", attributeNamespace: "", name: attribute.name, kind };
  if (spelling === "ASM")
    return {
      syntax: "kAsmLabel",
      attributeNamespace: "",
      name: attribute.name,
      kind,
    };
  const match = /^CXX(?::(\w+))?$/.exec(spelling);
  if (!match)
    throw new Error(`${attribute.name}: unknown spelling '${spelling}'`);
  return {
    syntax: "kCxx",
    attributeNamespace: match[1] ?? "",
    name: attribute.name,
    kind,
  };
}

function compareBytes(lhs: string, rhs: string): number {
  return Buffer.compare(Buffer.from(lhs), Buffer.from(rhs));
}

function compareSpellings(lhs: Spelling, rhs: Spelling): number {
  return (
    syntaxOrder.indexOf(lhs.syntax) - syntaxOrder.indexOf(rhs.syntax) ||
    compareBytes(lhs.attributeNamespace, rhs.attributeNamespace) ||
    compareBytes(lhs.name, rhs.name)
  );
}

function loadAttributes(): AttributeDef[] {
  const attributes = JSON.parse(
    fs.readFileSync(path.join(__dirname, "attributes.json"), "utf-8"),
  ) as AttributeDef[];

  const kindByScopedName = new Map<string, string>();
  for (const attribute of attributes) {
    if (!availabilities.has(attribute.availability))
      throw new Error(
        `${attribute.name}: unknown availability '${attribute.availability}'`,
      );
    if (attribute.optionalArguments && !attribute.arguments?.length)
      throw new Error(`${attribute.name}: optional arguments need arguments`);
    for (const spelling of attribute.spellings.map((s) =>
      spellingOf(attribute, s),
    )) {
      const scopedName = `${spelling.attributeNamespace}::${spelling.name}`;
      const previous = kindByScopedName.get(scopedName);
      if (previous && previous !== spelling.kind)
        throw new Error(
          `${scopedName}: the spelling names both ${previous} and ${spelling.kind}`,
        );
      kindByScopedName.set(scopedName, spelling.kind);
    }
  }

  const names = attributes.map((a) => a.name);
  if (new Set(names).size !== names.length)
    throw new Error("attributes.json: duplicate attribute names");

  return [...attributes].sort((a, b) => compareBytes(a.name, b.name));
}

const quote = (text: string) => JSON.stringify(text);

export function gen_attribute_kind_h({ output }: { output: string }) {
  const attributes = loadAttributes();

  const lines: string[] = [];
  lines.push(`// Generated by gen_attributes_h.ts`);
  lines.push(cpy_header);
  lines.push(``);
  lines.push(`#pragma once`);
  lines.push(``);
  lines.push(`namespace cxx {`);
  lines.push(``);
  lines.push(`enum class AttributeKind {`);
  for (const attribute of attributes) lines.push(`  ${kindOf(attribute)},`);
  lines.push(`};`);
  lines.push(``);
  lines.push(`}  // namespace cxx`);
  lines.push(``);

  fs.writeFileSync(output, lines.join("\n"));
}

export function gen_attributes_h({ output }: { output: string }) {
  const attributes = loadAttributes();

  const lines: string[] = [];
  lines.push(`// Generated by gen_attributes_h.ts`);
  lines.push(cpy_header);
  lines.push(``);
  lines.push(`#pragma once`);
  lines.push(``);
  lines.push(`namespace cxx::attribute_table {`);
  lines.push(``);

  const sorted: { spelling: Spelling; reference: string }[] = [];

  for (const attribute of attributes) {
    const kind = kindOf(attribute);
    const base = kind.slice(1);
    const spellings = attribute.spellings.map((s) => spellingOf(attribute, s));
    lines.push(`inline constexpr AttributeSpelling k${base}Spellings[] = {`);
    spellings.forEach((spelling, index) => {
      lines.push(
        `    {AttributeSyntax::${spelling.syntax}, ${quote(spelling.attributeNamespace)}, ${quote(spelling.name)}, AttributeKind::${kind}},`,
      );
      sorted.push({ spelling, reference: `&k${base}Spellings[${index}]` });
    });
    lines.push(`};`);
    lines.push(``);
    if (attribute.arguments?.length) {
      lines.push(
        `inline constexpr std::string_view k${base}Arguments[] = {${attribute.arguments.map(quote).join(", ")}};`,
      );
      lines.push(``);
    }
  }

  lines.push(`inline constexpr AttributeInfo kAttributeInfos[] = {`);
  for (const attribute of attributes) {
    const kind = kindOf(attribute);
    const base = kind.slice(1);
    const args = attribute.arguments?.length
      ? `k${base}Arguments`
      : `std::span<const std::string_view>{}`;
    lines.push(`    {`);
    lines.push(`        .kind = AttributeKind::${kind},`);
    lines.push(`        .name = ${quote(attribute.name)},`);
    lines.push(`        .spellings = k${base}Spellings,`);
    lines.push(
      `        .availability = AttributeAvailability::${availabilities.get(attribute.availability)},`,
    );
    lines.push(`        .cplusplusOnly = ${attribute.cplusplus === true},`);
    lines.push(`        .arguments = ${args},`);
    lines.push(
      `        .optionalArguments = ${attribute.optionalArguments === true},`,
    );
    lines.push(`        .subjects = ${quote(attribute.subjects)},`);
    lines.push(`        .documentation = ${quote(attribute.documentation)},`);
    lines.push(`    },`);
  }
  lines.push(`};`);
  lines.push(``);

  sorted.sort((a, b) => compareSpellings(a.spelling, b.spelling));
  lines.push(
    `inline constexpr const AttributeSpelling* kSortedAttributeSpellings[] = {`,
  );
  for (const { reference } of sorted) lines.push(`    ${reference},`);
  lines.push(`};`);
  lines.push(``);
  lines.push(`}  // namespace cxx::attribute_table`);
  lines.push(``);

  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, lines.join("\n"));
}
