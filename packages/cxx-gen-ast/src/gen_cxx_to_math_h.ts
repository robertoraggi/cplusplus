import { cpy_header } from "./cpy_header.ts";
import { BUILTINS, type BuiltinDef } from "./builtins.ts";
import * as fs from "node:fs";
import * as path from "node:path";

const builtinPrefix = "__builtin_";

const floatingKinds = new Map<string, string>([
  ["float", "kFloat"],
  ["double", "kDouble"],
  ["long double", "kLongDouble"],
]);

interface MathRewrite {
  callee: string;
  arity: number;
  floating: string;
  op: string;
}

function rewriteOf(builtin: BuiltinDef): MathRewrite {
  const prototype = Array.isArray(builtin.prototype)
    ? builtin.prototype[0]
    : builtin.prototype;
  const match = /^(?:constexpr )?(.+?) (\w+)\((.*)\)$/.exec(prototype ?? "");
  if (!match || match[2] !== builtin.name)
    throw new Error(`${builtin.name}: unexpected prototype '${prototype}'`);
  const [, result, , parameterList] = match;
  const parameters = parameterList.split(",").map((p) => p.trim());
  const floating = floatingKinds.get(result);
  if (!floating || parameters.some((p) => p !== result))
    throw new Error(
      `${builtin.name}: an 'mlir' rewrite needs a floating-point prototype with one type`,
    );
  if (!builtin.name.startsWith(builtinPrefix))
    throw new Error(`${builtin.name}: an 'mlir' rewrite needs a libcall name`);
  return {
    callee: builtin.name.slice(builtinPrefix.length),
    arity: parameters.length,
    floating,
    op: builtin.mlir!,
  };
}

export function gen_cxx_to_math_h({ output }: { output: string }) {
  const rewrites = BUILTINS.filter((b) => b.mlir)
    .map(rewriteOf)
    .sort((a, b) => a.callee.localeCompare(b.callee));

  const lines: string[] = [];
  lines.push(`// Generated by gen_cxx_to_math_h.ts`);
  lines.push(cpy_header);
  lines.push(``);
  lines.push(`#pragma once`);
  lines.push(``);
  lines.push(`namespace cxx::math_rewrites {`);
  lines.push(``);
  lines.push(`enum class FloatingKind { kFloat, kDouble, kLongDouble };`);
  lines.push(``);
  lines.push(`struct LibraryMathOp {`);
  lines.push(`  llvm::StringLiteral callee;`);
  lines.push(`  unsigned arity;`);
  lines.push(`  FloatingKind floating;`);
  lines.push(
    `  auto (*create)(mlir::OpBuilder&, mlir::Location, mlir::ValueRange)`,
  );
  lines.push(`      -> mlir::Value;`);
  lines.push(`};`);
  lines.push(``);
  lines.push(`inline constexpr LibraryMathOp kLibraryMathOps[] = {`);
  for (const r of rewrites) {
    lines.push(
      `    {"${r.callee}", ${r.arity}, FloatingKind::${r.floating},`,
    );
    lines.push(
      `     [](mlir::OpBuilder& builder, mlir::Location loc,`,
    );
    lines.push(`        mlir::ValueRange operands) -> mlir::Value {`);
    lines.push(
      `       return mlir::${r.op}::create(builder, loc, operands).getResult();`,
    );
    lines.push(`     }},`);
  }
  lines.push(`};`);
  lines.push(``);
  lines.push(`}  // namespace cxx::math_rewrites`);
  lines.push(``);

  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, lines.join("\n"));
}
